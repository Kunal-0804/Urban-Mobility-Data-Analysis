    COUNT(*) AS total_bookings,
    SUM(
        CASE
            WHEN `Booking Status` = 'Completed' THEN 1
            ELSE 0
        END
    ) AS completed_bookings,
    ROUND(
        SUM(
            CASE
                WHEN `Booking Status` = 'Completed' THEN 1
                ELSE 0
            END
